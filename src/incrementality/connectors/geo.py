def zip_to_dma(zip_code: str) -> str | None:
    """Map a 5-digit zip code to its DMA code.

    Uses the first 3 digits (zip3 prefix) for lookup.
    Returns None if no mapping is found.
    """
    if not zip_code or len(zip_code) < 3:
        return None
    prefix = zip_code[:3]
    return _ZIP3_TO_DMA.get(prefix)


def get_zip3_to_dma_map() -> dict[str, str]:
    """Return the full zip3 → DMA mapping."""
    return dict(_ZIP3_TO_DMA)
